# gen_replay.py -- simulated 8-week resting HR (seed 37). Writes replay_data.h
import random

SEED, DAYS, LOCK_AFTER, AMBER_PCT, SUSTAIN = 37, 56, 10, 10, 3

def make_values():
    rng = random.Random(SEED)
    vals = []
    for d in range(DAYS):                 # d = 0..55
        v = 63 + rng.randint(-1, 1)       # resting HR with small noise
        if d >= 30:                       # slow rise starts at day 31
            v = 63 + ((d - 30) * 7) // 11 # clean ramp, no noise yet
        vals.append(v)
    return vals

def median7(w):
    return sorted(w)[3]

def amber_day(vals):
    base = sum(vals[:LOCK_AFTER]) // LOCK_AFTER
    run = 0
    for i in range(DAYS):
        if i >= 6:                                   # needs 7 values
            med = median7(vals[i-6:i+1])
            run = run + 1 if (med - base) * 100 // base >= AMBER_PCT else 0
            if run >= SUSTAIN:
                return base, i + 1                   # days numbered 1..56
    return base, None

vals = make_values()
base, day = amber_day(vals)
print("baseline:", base)
print("values:", vals)
print("amber day:", day)

with open("replay_data.h", "w") as f:
    f.write("/* generated by gen_replay.py, seed 37, SIMULATED */\n")
    f.write("static const int32_t replay_hr[56] = {\n    ")
    f.write(", ".join(str(v) for v in vals))
    f.write("\n};\n")